<?php

namespace app\admin\controller;

use think\App;

class HealthHomeController extends ToolController
{
    public function __construct(App $app)
    {
        parent::__construct($app);

        $this->model = new \app\admin\model\health\HealthHomeModel();
    }


    public function setWhere()
    {
        $name = $this->request->param('name', '', 'trim');
        $status = $this->request->param('status', '', 'trim');
        $start_time = $this->request->param('start_time', '', 'trim');
        $end_time = $this->request->param('end_time', '', 'trim');

        $where = [];
        if ($name) {
            $where[] = ['name', 'like', '%' . $name . '%'];
        }
        $where[]= ['type','=',1];

        $this->assign('status', $status);
        return $where;
    }

    //子分类列表
    public function manage_index()
    {
        $where  = [];
        $where[]= ['type','=',2];
        $list = $this->model->where($where)->paginate(10);
        return $this->fetch('manage_index', ['list' => $list,'page'=>$list->render()]);
    }

    public function update()
    {
        $this->assign('exam_list', cmf_table('exam')->field('id,name')->select());
        return parent::update(); // TODO: Change the autogenerated stub
    }


    /**编辑页面
     * @return mixed
     */
    public function  manage_update()
    {
        $params = $this->request->param();

        $this->assign('params', $params);
        //$this->outDate();
        if (empty($params['id'])) {
            return $this->fetch();
        }
        $item = $this->setEdit($params);
        if (!empty($item['content'])) {
            $item['content'] = htmlspecialchars_decode($item['content']);
        }
        $item = $this->getParamData($item);
        $this->assign('item', $item);


        return $this->fetch();
    }

    /**编辑提交
     * @return void
     */
    public function  manage_updatePost()
    {
        if ($this->request->isAjax()) {
            $params = $this->request->param();
            $params = $this->setParamData($params);

            if ($params['id'] != 6) {
                $params['is_exam'] = 1;
                $params['is_demand'] = 2;
            }else{
                $params['is_exam'] = 2;
                $params['is_demand'] = 2;
            }

            if (empty($params['id'])) {
                $result = $this->setAddPost($params);
            } else {
                $result = $this->setEditPost($params);
            }
            $this->getMsg(!empty($result));
        } else {
            $this->error('非法请求');
        }
    }


}