<?php

namespace app\admin\controller;

use api\wxapp\model\CommonModel;
use app\admin\model\member\CommunityModel;
use think\App;

class CommunityController extends ToolController
{
    public function __construct(App $app)
    {
        parent::__construct($app);
        $this->model = new CommunityModel();
    }


    public function getList($item)
    {
        $item['province_name'] = CommonModel::getAreaName($item['province']);
        $item['city_name'] = CommonModel::getAreaName($item['city']);
        $item['county_name'] = CommonModel::getAreaName($item['county']);

        return parent::getList($item); // TODO: Change the autogenerated stub
    }


    //获取省市区选择的数据
    public function getJsonAreaList()
    {
        $pid = $this->request->param('pid', 0);
        $map = [];
        $AreaModel = new AreaModel();
        if ($pid != 0) {
            $pid = $AreaModel->where(['code' => $pid])->value('id');
        }
        $map['pid'] = $pid;
        $result = $AreaModel->field('id,name,code')->where($map)->select();

        $this->success('', '', $result);
    }

}