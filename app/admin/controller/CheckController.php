<?php

namespace app\admin\controller;

use app\admin\model\member\CheckModel;
use think\App;

class CheckController extends ToolController
{
    public function __construct(App $app)
    {
        parent::__construct($app);
        $this->model = new CheckModel();
    }


    public function getList($item)
    {
        $item['status_name'] = $this->model->get_status()[$item['status']]??'';
        $item['active_name'] = $this->model->get_type()[$item['active_type']]??'';
        return $item; // TODO: Change the autogenerated stub
    }
}