    public function updatePost()
    {
        if ($this->request->isAjax()) {
            $params = $this->request->param();
            $params = $this->setParamData($params);
//            if (empty($params['password'])) $this->error('密码不能为空');
            if (empty($params['avatar'])) $params['avatar'] = cmf_get_option('set_config')['app_logo'];

            if (empty($params['id'])) {
                $info = $this->model->where('mobile', $params['mobile'])->find();
                if ($info) $this->error('手机号已存在');
                $params['openid'] = md5('wjb' . time());
                $params['vcode'] = CommonModel::get_vcode();
                $result = $this->setAddPost($params);
            } else {
                $info = $this->model->where('mobile', $params['mobile'])
                    ->where('id', '<>', $params['id'])->find();
                if ($info) $this->error('手机号已存在');
                $result = $this->setEditPost($params);
            }
            $this->getMsg(!empty($result));
        } else {
            $this->error('非法请求');
        }
    }

    public function outData(){
        // 导出条件与 index 保持一致：相同的筛选 + 排序，确保导出的就是当前列表看到的数据
        $params = $this->request->param();
        $keyword = $this->request->param('keyword','','trim');
        $sortField = $this->request->param('sort_field','id','trim');
        $sortOrder = $this->request->param('sort_order','desc','trim');

        $map = [];
        $map[] = ['a.status','>',0]; // 与 index 一致
        if(!empty($keyword)){
            $map[] = ['a.nickname|a.mobile','like',"%".$keyword."%"];
        }
        if(!empty($params['community_id'])){
            $map[] = ['community_id','=',$params['community_id']];
        }
        if(!empty($params['type'])){
            $map[] = ['a.type','=',$params['type']];
        }
        if(!empty($params['id'])){
            $map[] = ['a.id','=',$params['id']];
        }
        $start_time = $this->request->param('start_time','','trim');
        $end_time = $this->request->param('end_time','','trim');
        if($start_time) $map[] = ['a.create_time','>=',strtotime($start_time)];
        if($end_time) $map[] = ['a.create_time','<=',strtotime($end_time)+86399];

        // 验证排序字段，与 index 保持一致
        if (!in_array($sortField, ['id', 'point', 'create_time'])) {
            $sortField = 'id';
        }
        $list_order = 'a.' . $sortField . ' ' . $sortOrder;

        // ===== 性能优化（导出慢的根因） =====
        // 原实现：先查出全部用户，再在 foreach 里对每一行分别查小区、社区名称，
        // 每行 2 条 SQL，2.7 万用户 ≈ 5.4 万次查询，接口要等几十秒。
        // 现改为一次 LEFT JOIN 取全量数据，并且只取导出用到的 7 个字段（原来 a.* 有 36 个）。
        // 名称表在 ON 条件里带上 delete_time = 0，与 ToolModel 软删除的取数口径保持一致。
        $list = Db::name('member')->alias('a')
            ->leftJoin('member_community_parent cp', 'cp.id = a.community_parent_id AND cp.delete_time = 0')
            ->leftJoin('member_community c', 'c.id = a.community_id AND c.delete_time = 0')
            ->field('a.id,a.nickname,a.mobile,a.point,a.create_time,cp.name AS community_parent_name,c.name AS community_name')
            ->where($map)
            ->order($list_order)
            ->select();

        $rows = [];
        foreach ($list as $item) {
            $rows[] = [
                'id'                    => $item['id'],
                'nickname'              => $item['nickname'],
                'community_parent_name' => $item['community_parent_name'] ?? '',
                'community_name'        => $item['community_name'] ?? '',
                'mobile'                => $item['mobile'],
                'point'                 => $item['point'],
                'create_time'           => date('Y-m-d H:i:s', (int)$item['create_time']),
            ];
        }

        $filename = '用户列表'.date('Y-m-d');
        $head = ['用户ID','昵称','社区','小区','手机号','积分','注册日期'];//设置表头
        $keys = ['id','nickname','community_parent_name','community_name','mobile','point','create_time'];//设置表头
        // 注意：CommonModel::outData 是 static 静态方法，必须用 :: 调用。
        // 不可使用 $obj->outData() 这种实例调用方式，否则 ThinkPHP Model 的 __call 魔术方法
        // 会把 outData 转发到查询构造器 $this->db()->outData()，进而对 cmf_common_model 表发起查询导致报错。
        CommonModel::outData($filename,$rows,$head,$keys);
    }


    public function addBalance()
    {
        $id = $this->request->param('id');
        if ($this->request->isPost()) {
            $account_type = $this->request->param('account_type', 1);
            $direction = $this->request->param('direction');
            $change = $this->request->param('change');
            $remark = $this->request->param('remark');

            if ($direction == 2) {
                $change = -$change;
            }
            $item =MemberModel::where('id', $id)->find();
            //balance
            //point
            //commission
            if ($account_type == 1) {
                if ($direction == 2) $item['balance'] < -$change && $this->error('余额不能调整为负');
                AccountLogModel::add_account_log($id, 1, 110, $change, ['remark' => $remark]);
            } elseif ($account_type == 2) {
                if ($direction == 2) $item['point'] < -$change && $this->error('余额不能调整为负');
                AccountLogModel::add_account_log($id, 2, 210, $change, ['remark' => $remark]);
            } elseif ($account_type == 4) {
                if ($direction == 2) $item['commission'] < -$change && $this->error('余额不能调整为负');
                AccountLogModel::add_account_log($id, 4, 410, $change, ['remark' => $remark]);
            }
            $this->success('操作成功');

        } else {
            $this->assign('id', $id);
            return $this->fetch();
        }
    }

    public function addMany()
    {
        $c_id = $this->request->param('c_id');
        $this->assign('c_id', $c_id);

        if ($this->request->isPost()) {
            //获取表格的大小，限制上传表格的大小5M
            $file_size = $_FILES['myfile']['size'];
            if ($file_size > 5 * 1024 * 1024) {
                $this->error('文件大小不能超过5M');
                exit();
            }


            //限制上传表格类型
            $fileExtendName = substr(strrchr($_FILES['myfile']["name"], '.'), 1);
            //application/vnd.ms-excel  为xls文件类型
            if ($fileExtendName != 'xls' && $fileExtendName != 'xlsx') {
                $this->error('必须为excel表格');
                exit();
            }

            if (is_uploaded_file($_FILES['myfile']['tmp_name'])) {
                // 有Xls和Xlsx格式两种
                $objReader = IOFactory::createReader('Xlsx');

                $filename = $_FILES['myfile']['tmp_name'];
                $objPHPExcel = $objReader->load($filename);  //$filename可以是上传的表格，或者是指定的表格
                $sheet = $objPHPExcel->getSheet(0);   //excel中的第一张sheet
                $highestRow = $sheet->getHighestRow();       // 取得总行数
                if ($highestRow < 2) error_log('表格数据为空');
                $data_i = [];
                $keys = ['A' => 'mobile'];
                //循环读取excel表格，整合成数组。如果是不指定key的二维，就用$data[i][j]表示。
                for ($j = 2; $j <= $highestRow; $j++) {
                    foreach ($keys as $k => $item) {
                        $data_i[$j][$item] = trim($objPHPExcel->getActiveSheet()->getCell($k . $j)->getValue());
                    }

                    if (empty($data_i[$j][$item])) {
                        $this->error($k . $j . '存在数据为空');
                    }
                    if (!preg_match("/^1[3456789]{1}\d{9}$/", $data_i[$j]['mobile'])) {
                        $this->error($k . $j . '不是手机号');
                    }
                    $is = $this->model->where(['mobile' => $data_i[$j]['mobile'], 'c_id' => $c_id])->count();
                    if ($is > 0) {
                        $this->error('第' . $j . '手机号已存在');
                    }
                    $data_i[$j]['create_time'] = time();

                }


                $this->model->insertAll($data_i);
                $this->success('导入成功！');

            }
        }


    }

