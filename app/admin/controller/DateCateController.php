<?php

namespace app\admin\controller;

use app\admin\model\course\CourseChapterModel;
use think\App;

class DateCateController extends ToolController
{
    public function __construct(App $app)
    {
        parent::__construct($app);
        $this->model = new CourseChapterModel();
    }

    protected $date_id = 'd_id';// 子分类 上级的字段
    public function setWhere()
    {
        $data_id = $this->request->param('data_id');
        $title = $this->request->param('name');
        $where = [];

        if (!empty($data_id)) {
            $where[] = [$this->date_id, '=', trim($data_id)];
        }
        if (!empty($title)) {
            $where[] = ['name', 'like', '%' . trim($title) . '%'];
        }

        $this->assign('data_id', $data_id);
        $this->assign('name', $title);
        return $where;
    }


    public function update()
    {
        $data_id = $this->request->param('data_id');
        $this->assign('data_id', $data_id);

        return parent::update(); // TODO: Change the autogenerated stub
    }

    public function updatePost()
    {
        $data_id = $this->request->param('data_id');
        $this->assign('data_id', $data_id);
        if ($this->request->isAjax()) {
            $params = $this->request->param();
            $params[$this->date_id] = $data_id;
            if (empty($params['id'])) {
                $result = $this->setAddPost($params);
            } else {
                $result = $this->setEditPost($params);
            }
            $this->getMsg(!empty($result));
        } else {
            $this->error('非法请求');
        }
    }
}