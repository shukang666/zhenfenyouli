<?php

namespace app\admin\controller;

use app\admin\model\basic\NewsCateModel;
use app\admin\model\basic\NewsModel;
use think\App;

class NewsController extends ToolController
{
    public function __construct(App $app)
    {
        parent::__construct($app);
        $this->model = new NewsModel();
        $this->cate_model =new NewsCateModel();
    }

    public function setWhere()
    {
        $params = $this->request->param();
        $where = [];


        if (!empty($params['name'])) {
            $where[] = ['name', 'like', '%' . trim($params['name']) . '%'];
        }
        if (!empty($params['cate_id'])) $where[] = ['cate_id', '=', $params['cate_id']];
        $this->get_params();
        return $where;
    }


    public function getList($item)
    {
        $item['cate_name'] = $this->cate_model->where('id', $item['cate_id'])->value('cate_name');
        return $item; // TODO: Change the autogenerated stub
    }

    public function index1()
    {
        return redirect((string)url('index', ['cate_id' => 1]));
    }

    public function park_index()
    {
        return redirect((string)url('index', ['cate_id' => 2]));
    }


    public function get_params()
    {
        $cate_list = cmf_table('news_cate')->select();
        $this->assign('cate_list', $cate_list);
    }


     //子分类列表
    public function cate_list()
    {
        $keyword = $this->request->param('keyword');
        $where = [];
        if ($keyword) {
            $where[] = ['name', 'like', '%' . $keyword . '%'];
        }
        $pid = $this->request->param('pid');
        $list = $this->cate_model->where($where)->paginate(10);
        return $this->fetch('cate_list', ['list' => $list, 'page' => $list->render()]);
    }
//子分类添加编辑页面
    public function cate_update()
    {

        $pid = $this->request->param('pid');
        $id = $this->request->param('id');
        if (empty($id)) {
            return $this->fetch('cate_update', ['pid' => $pid]);
        } else {
            $item = $this->cate_model->find($id);
            return $this->fetch('cate_update', ['item' => $item, 'pid' => $pid]);
        }

    }

    //子分类添加编辑提交
    public function cate_update_post()
    {
        $data = $this->request->param();
        if (empty($data['id'])) {
            $this->cate_model->save($data);
            $this->success('添加成功');
        } else {
            $this->cate_model->update($data, ['id' => $data['id']]);
            $this->success('修改成功');
        }

    }
}